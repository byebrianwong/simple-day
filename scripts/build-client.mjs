// Bundles the display page's script and stylesheet into
// lib/generated/display-assets.ts, which the page route inlines, and the
// service worker into lib/generated/sw-asset.ts, which app/sw.js/route.ts
// serves.
// The target is old on purpose: the iPad may be an old one. Safari 11 is the
// lowest target esbuild can produce (it cannot rewrite let/const for Safari
// 10, although Safari 10 runs this code's use of them).
//
//   node scripts/build-client.mjs          build once
//   node scripts/build-client.mjs --watch  rebuild on change (used by npm run dev)

import * as esbuild from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const outFile = path.join(root, 'lib', 'generated', 'display-assets.ts');
const swOutFile = path.join(root, 'lib', 'generated', 'sw-asset.ts');
const target = ['safari11', 'ios11', 'chrome64'];
const BUDGET_GZIP_BYTES = 100 * 1024;

const common = { bundle: true, minify: true, write: false, target, logLevel: 'warning', legalComments: 'none' };

async function buildOnce() {
  const [js, css, sw] = await Promise.all([
    esbuild.build({ ...common, entryPoints: [path.join(root, 'client', 'display.ts')], format: 'iife' }),
    esbuild.build({ ...common, entryPoints: [path.join(root, 'client', 'display.css')] }),
    esbuild.build({ ...common, entryPoints: [path.join(root, 'client', 'sw.ts')], format: 'iife' }),
  ]);
  // The script is inlined in a <script> tag, so it must not close it early.
  const jsText = js.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const cssText = css.outputFiles[0].text.replace(/<\/style/gi, '<\\/style');
  mkdirSync(path.dirname(outFile), { recursive: true });
  writeFileSync(
    outFile,
    '// Generated by scripts/build-client.mjs. Do not edit.\n' +
      `export const DISPLAY_JS = ${JSON.stringify(jsText)};\n` +
      `export const DISPLAY_CSS = ${JSON.stringify(cssText)};\n`,
  );
  const swText = sw.outputFiles[0].text;
  writeFileSync(
    swOutFile,
    '// Generated by scripts/build-client.mjs. Do not edit.\n' + `export const SW_JS = ${JSON.stringify(swText)};\n`,
  );
  const gz = gzipSync(jsText).length;
  console.log(
    `display script: ${jsText.length} bytes, ${gz} gzipped; stylesheet: ${cssText.length} bytes; ` +
      `service worker: ${swText.length} bytes`,
  );
  if (gz > BUDGET_GZIP_BYTES) {
    throw new Error(`display script is ${gz} bytes gzipped, over the ${BUDGET_GZIP_BYTES} byte budget`);
  }
}

await buildOnce();

if (process.argv.includes('--watch')) {
  const { watch } = await import('node:fs');
  let timer = null;
  for (const dir of ['client', 'lib']) {
    watch(path.join(root, dir), { recursive: true }, (_event, file) => {
      if (!file || String(file).includes('generated')) return;
      clearTimeout(timer);
      timer = setTimeout(() => buildOnce().catch((err) => console.error(err.message)), 100);
    });
  }
  console.log('watching client/ and lib/ for changes');
}
