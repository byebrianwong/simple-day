// Copies the event icons from the lucide-static package into
// lib/icon-shapes.ts. Run after changing ICONS below or the keyword list in
// lib/event-icons.ts:
//
//   node scripts/update-icons.mjs
//
// Lucide is ISC licensed; the notice is copied into the output file.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const iconDir = path.join(root, 'node_modules', 'lucide-static', 'icons');
const pkg = JSON.parse(readFileSync(path.join(root, 'node_modules', 'lucide-static', 'package.json'), 'utf8'));

export const ICONS = [
  'bath', 'bed', 'book-open', 'bus', 'cake', 'car', 'church', 'coffee', 'dices', 'dumbbell', 'flower-2',
  'footprints', 'gift', 'glasses', 'landmark', 'mail', 'music', 'paw-print', 'party-popper', 'phone', 'pill',
  'plane', 'scissors', 'shirt', 'shopping-cart', 'spray-can', 'stethoscope', 'toothbrush', 'trash-2', 'tv',
  'users', 'utensils',
];

const shapes = {};
for (const name of ICONS) {
  const svg = readFileSync(path.join(iconDir, name + '.svg'), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s*\/>/g, '/>');
  shapes[name] = inner;
}

// Lucide's licence, copied word for word into the output.
const license = readFileSync(path.join(root, 'node_modules', 'lucide-static', 'LICENSE'), 'utf8')
  .trim()
  .split('\n')
  .map((line) => ('// ' + line).trimEnd())
  .join('\n');

const out =
  '// Generated by scripts/update-icons.mjs from lucide-static ' + pkg.version + '. Do not edit.\n' +
  '// Icons from Lucide (https://lucide.dev). Each value is the inside of a\n' +
  '// 24x24 SVG drawn with a 2-unit stroke.\n' +
  '//\n' +
  license + '\n\n' +
  'export const ICON_SHAPES: { [name: string]: string } = ' + JSON.stringify(shapes, null, 2) + ';\n';
writeFileSync(path.join(root, 'lib', 'icon-shapes.ts'), out);
console.log('wrote ' + ICONS.length + ' icons to lib/icon-shapes.ts');
